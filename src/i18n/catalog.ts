export type ExtraKey = keyof typeof catalog;

export function extraDictionary(locale: 'tr' | 'en' | 'ar' | 'es') {
  return Object.fromEntries((Object.keys(catalog) as ExtraKey[]).map((key) => {
    const row = catalog[key] as { tr: string; en: string; ar: string; es?: string };
    const value = locale === 'es' ? (row.es ?? row.en) : row[locale];
    return [key, value];
  })) as Record<ExtraKey, string>;
}
