const dictionaries = {
  tr: { ...base.tr, ...extraDictionary('tr') },
  en: { ...base.en, ...extraDictionary('en') },
  ar: { ...base.ar, ...extraDictionary('ar') },
};

export type I18nKey = keyof (typeof base)['tr'] | ExtraKey;

type I18nState = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
};

export const useI18nStore = create<I18nState>()(
  persist(
    (set) => ({
      locale: 'tr',
      setLocale: (locale) => set({ locale }),
    }),
    { name: 'safdas-locale', storage: createJSONStorage(() => AsyncStorage) },
  ),
);

export function translate(locale: Locale, key: I18nKey, vars?: Record<string, string | number>) {
  let value: string = dictionaries[locale][key];
  if (!vars) return value;
  for (const [name, replacement] of Object.entries(vars)) {
    value = value.split(`{${name}}`).join(String(replacement));
  }
  return value;
}

export function useT() {
  const locale = useI18nStore((state) => state.locale);
  return useCallback((key: I18nKey, vars?: Record<string, string | number>) => translate(locale, key, vars), [locale]);
}
