export type JobTextKey = keyof typeof DICT;

export function jobText(locale: Locale, key: JobTextKey, vars?: Record<string, string | number>): string {
  const row = DICT[key];
  let value: string = locale === 'tr' ? row[0] : row[1];
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.split(`{${name}}`).join(String(replacement));
    }
  }
  return value;
}

export function useJobT() {
  const locale = useI18nStore((state) => state.locale);
  return useCallback(
    (key: JobTextKey, vars?: Record<string, string | number>) => jobText(locale, key, vars),
    [locale],
  );
}

export function mapJobError(error: unknown, locale: Locale): string {
  const raw = error instanceof Error ? error.message : String(error ?? '');
  const normalized = raw.toLowerCase();
  const pick = (key: JobTextKey) => jobText(locale, key);
  if (normalized.includes('job_profile_required')) return pick('errorProfileRequired');
  if (normalized.includes('already_applied')) return pick('errorAlreadyApplied');
  if (normalized.includes('listing_limit_reached')) return pick('errorListingLimit');
  if (normalized.includes('employer_pro_required')) return pick('errorProRequired');
  if (normalized.includes('plus_required')) return pick('errorPlusRequired');
  if (normalized.includes('quota_exceeded')) return pick('errorQuotaExceeded');
  if (normalized.includes('user_blocked')) return pick('errorBlocked');
  if (normalized.includes('invitation_declined')) return pick('errorInviteDeclined');
  if (normalized.includes('employer_not_accepting')) return pick('errorEmployerNotAccepting');
  if (normalized.includes('cv_not_found')) return pick('errorCvNotFound');
  if (normalized.includes('invalid_interview_time')) return pick('errorInvalidInterviewTime');
  if (normalized.includes('not_allowed')) return pick('errorNotAllowed');
  if (normalized.includes('not_authenticated') || normalized.includes('conversation_unavailable')) return pick('errorGeneric');
  if (normalized.includes('listing_not_open') || normalized.includes('listing_expired')) return pick('errorListingNotOpen');
  if (normalized.includes('application_deadline')) return pick('errorApplicationDeadline');
  if (normalized.includes('member_limit')) return pick('errorMemberLimit');
  if (normalized.includes('already_invited')) return pick('errorAlreadyInvited');
  if (normalized.includes('location_in_use')) return pick('errorLocationInUse');
  if (normalized.includes('invalid_status_transition')) return pick('errorGeneric');
  if (normalized.includes('failed to fetch') || normalized.includes('network')) return pick('errorGeneric');
  return raw || pick('errorGeneric');
}
